import mongoose from 'mongoose';

const scenarioSchema = new mongoose.Schema(
  {
    title: { type: String, required: true, maxlength: 200 },
    optionA: { type: String, required: true, maxlength: 300 },
    optionB: { type: String, required: true, maxlength: 300 },
  },
  { _id: true }
);

const futureProfileSchema = new mongoose.Schema(
  {
    user: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },
    dream: { type: mongoose.Schema.Types.ObjectId, ref: 'Dream', required: true, unique: true },
    career: { type: String, maxlength: 200, default: '' },
    cityTheme: { type: String, required: true, maxlength: 60 },
    roomTheme: { type: String, required: true, maxlength: 60 },
    lifestyle: { type: String, maxlength: 200, default: '' },
    summary: { type: String, required: true, maxlength: 800 },
    scenarios: { type: [scenarioSchema], default: [] },
    // 'template' = built from simple rules; 'ai' = generated by the AI service (Phase 5).
    source: { type: String, enum: ['template', 'ai'], default: 'template' },
    disclaimer: {
      type: String,
      default: 'An imaginative simulation, not a prediction of your real future.',
    },
  },
  { timestamps: true }
);

export const FutureProfile =
  mongoose.models.FutureProfile || mongoose.model('FutureProfile', futureProfileSchema);
